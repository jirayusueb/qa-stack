#!/usr/bin/env node
// Build the skill dependency graph, detect cycles and dangling references,
// and generate docs/skill-graph.md. `--check` compares instead of writing.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const DOC = 'docs/skill-graph.md';

const skills = readdirSync(join(ROOT, 'skills'))
  .filter((name) => statSync(join(ROOT, 'skills', name)).isDirectory())
  .sort();
const skillSet = new Set(skills);

function references(text) {
  const found = new Set();
  const patterns = [
    /\.\.\/([a-z0-9][a-z0-9-]*)\/SKILL\.md/g,
    /skills\/([a-z0-9][a-z0-9-]*)\/SKILL\.md/g,
    /`skill:\/\/([a-z0-9][a-z0-9-]*)`/g,
    /`\/skill:([a-z0-9][a-z0-9-]*)`/g,
  ];
  for (const pattern of patterns) {
    let match;
    while ((match = pattern.exec(text)) !== null) found.add(match[1]);
  }
  return [...found];
}

function playbookReferences(playbookText) {
  const found = new Set();
  const pattern = /\*\*([a-z0-9][a-z0-9-]*)\*\*/g;
  let match;
  while ((match = pattern.exec(playbookText)) !== null) found.add(match[1]);
  return [...found];
}

const edges = [];
const dangling = [];
for (const skill of skills) {
  const text = readFileSync(join(ROOT, 'skills', skill, 'SKILL.md'), 'utf8');
  for (const target of references(text)) {
    if (target === skill) continue;
    if (!skillSet.has(target)) {
      dangling.push({ from: skill, to: target });
      continue;
    }
    edges.push({ from: skill, to: target });
  }
}

// Playbooks run skills in order. Add those as dependencies of qa-mode.
const playbookDir = join(ROOT, 'skills/qa-mode/playbooks');
if (existsSync(playbookDir)) {
  for (const file of readdirSync(playbookDir).filter((name) => name.endsWith('.md'))) {
    const text = readFileSync(join(playbookDir, file), 'utf8');
    for (const target of playbookReferences(text)) {
      if (!skillSet.has(target) || target === 'qa-mode') continue;
      edges.push({ from: 'qa-mode', to: target, via: `playbooks/${file}` });
    }
  }
}

const unique = new Map();
for (const edge of edges) unique.set(`${edge.from}->${edge.to}`, edge);
const graphEdges = [...unique.values()];

// Tarjan cycle detection.
function cycles() {
  const adjacency = new Map(skills.map((name) => [name, []]));
  for (const edge of graphEdges) adjacency.get(edge.from)?.push(edge.to);
  let index = 0;
  const stack = [];
  const onStack = new Set();
  const indices = new Map();
  const low = new Map();
  const result = [];
  function visit(node) {
    indices.set(node, index);
    low.set(node, index);
    index += 1;
    stack.push(node);
    onStack.add(node);
    for (const next of adjacency.get(node) ?? []) {
      if (!indices.has(next)) {
        visit(next);
        low.set(node, Math.min(low.get(node), low.get(next)));
      } else if (onStack.has(next)) {
        low.set(node, Math.min(low.get(node), indices.get(next)));
      }
    }
    if (low.get(node) === indices.get(node)) {
      const component = [];
      let current;
      do {
        current = stack.pop();
        onStack.delete(current);
        component.push(current);
      } while (current !== node);
      if (component.length > 1) result.push(component.sort());
    }
  }
  for (const node of skills) if (!indices.has(node)) visit(node);
  return result;
}

const foundCycles = cycles();
const allow = existsSync(join(ROOT, 'scripts/skill-graph.allowed.json'))
  ? JSON.parse(readFileSync(join(ROOT, 'scripts/skill-graph.allowed.json'), 'utf8'))
  : { cycles: [] };
const allowedCycles = new Set(allow.cycles.map((cycle) => cycle.join(',')));
const unallowed = foundCycles.filter((cycle) => !allowedCycles.has(cycle.join(',')));

function markdown() {
  const lines = [
    '# Skill dependency graph',
    '',
    'Generated by `scripts/skill-graph.mjs`. Do not edit by hand.',
    '',
    `- Skills: ${skills.length}`,
    `- Edges: ${graphEdges.length}`,
    `- Cycles: ${foundCycles.length}`,
    `- Dangling references: ${dangling.length}`,
    '',
    '## Graph',
    '',
    '```mermaid',
    'graph LR',
  ];
  for (const edge of graphEdges.sort((a, b) => `${a.from}${a.to}`.localeCompare(`${b.from}${b.to}`))) {
    lines.push(`  ${edge.from} --> ${edge.to}`);
  }
  lines.push('```', '', '## Cycles', '');
  if (!foundCycles.length) lines.push('None.');
  for (const cycle of foundCycles) lines.push(`- ${cycle.join(' -> ')} -> ${cycle[0]}`);
  lines.push('', '## Dangling references', '');
  if (!dangling.length) lines.push('None.');
  for (const item of dangling) lines.push(`- ${item.from} -> ${item.to}`);
  lines.push('');
  return lines.join('\n');
}

const output = markdown();
if (CHECK) {
  const problems = [];
  if (unallowed.length) {
    for (const cycle of unallowed) problems.push(`cycle without an allowlist entry: ${cycle.join(' -> ')}`);
  }
  if (dangling.length) {
    for (const item of dangling) problems.push(`dangling reference: ${item.from} -> ${item.to}`);
  }
  if (!existsSync(join(ROOT, DOC))) problems.push(`${DOC} is missing; run node scripts/skill-graph.mjs`);
  else if (readFileSync(join(ROOT, DOC), 'utf8') !== output) problems.push(`${DOC} is stale; run node scripts/skill-graph.mjs`);
  if (problems.length) {
    console.error(`skill-graph --check: ${problems.length} problem(s)`);
    for (const problem of problems) console.error(`- ${problem}`);
    process.exit(1);
  }
  console.log(`skill-graph --check: ok (${skills.length} skills, ${graphEdges.length} edges, ${foundCycles.length} cycles)`);
  process.exit(0);
}
writeFileSync(join(ROOT, DOC), output);
console.log(`skill-graph: wrote ${DOC} (${skills.length} skills, ${graphEdges.length} edges, ${foundCycles.length} cycles, ${dangling.length} dangling)`);
if (dangling.length) process.exitCode = 1;
